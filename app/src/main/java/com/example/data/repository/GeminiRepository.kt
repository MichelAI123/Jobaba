package com.example.data.repository

import android.util.Log
import com.example.BuildConfig
import com.example.data.model.*
import com.example.data.remote.RetrofitClient
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

class GeminiRepository {
    private val apiKey: String
        get() = try {
            BuildConfig.GEMINI_API_KEY
        } catch (e: Exception) {
            ""
        }

    suspend fun generateWithHighThinking(prompt: String, systemInstruction: String? = null): Result<String> = withContext(Dispatchers.IO) {
        if (apiKey.isBlank() || apiKey == "MY_GEMINI_API_KEY") {
            return@withContext Result.failure(Exception("Gemini API key is not configured. Please add GEMINI_API_KEY to AI Studio Secrets panel."))
        }
        try {
            val request = GeminiGenerateRequest(
                contents = listOf(
                    GeminiContent(
                        role = "user",
                        parts = listOf(GeminiPart(text = prompt))
                    )
                ),
                generationConfig = GeminiGenerationConfig(
                    thinkingConfig = GeminiThinkingConfig(thinkingLevel = "high")
                ),
                systemInstruction = systemInstruction?.let {
                    GeminiContent(parts = listOf(GeminiPart(text = it)))
                }
            )
            val response = RetrofitClient.geminiService.generateContent("gemini-3.1-pro-preview", apiKey, request)
            val text = response.candidates?.firstOrNull()?.content?.parts?.firstOrNull()?.text
                ?: "No response generated by gemini-3.1-pro-preview."
            Result.success(text)
        } catch (e: Exception) {
            Log.e("GeminiRepository", "High Thinking error: ${e.message}", e)
            Result.failure(e)
        }
    }

