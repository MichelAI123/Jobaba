    suspend fun generateImage(prompt: String, imageSize: String = "1K"): Result<String> = withContext(Dispatchers.IO) {
        if (apiKey.isBlank() || apiKey == "MY_GEMINI_API_KEY") {
            return@withContext Result.failure(Exception("Gemini API key is not configured. Please add GEMINI_API_KEY to AI Studio Secrets panel."))
        }
        try {
            val request = GeminiGenerateRequest(
                contents = listOf(
                    GeminiContent(
                        role = "user",
                        parts = listOf(GeminiPart(text = prompt))
                    )
                ),
                generationConfig = GeminiGenerationConfig(
                    imageConfig = GeminiImageConfig(aspectRatio = "1:1", imageSize = imageSize),
                    responseModalities = listOf("TEXT", "IMAGE")
                )
            )
            val response = RetrofitClient.geminiService.generateContent("gemini-3-pro-image-preview", apiKey, request)
            val candidate = response.candidates?.firstOrNull()
            val textPart = candidate?.content?.parts?.firstOrNull { it.text != null }?.text ?: ""
            val imagePart = candidate?.content?.parts?.firstOrNull { it.inlineData != null }
            if (imagePart?.inlineData != null) {
                Result.success("data:${imagePart.inlineData.mimeType};base64,${imagePart.inlineData.data}")
            } else {
                Result.success(textPart.ifBlank { "Image generation request processed." })
            }
        } catch (e: Exception) {
            Log.e("GeminiRepository", "Image Generation error: ${e.message}", e)
            Result.failure(e)
        }
    }

    suspend fun generateTTS(text: String): Result<String> = withContext(Dispatchers.IO) {
        if (apiKey.isBlank() || apiKey == "MY_GEMINI_API_KEY") {
            return@withContext Result.failure(Exception("Gemini API key is not configured. Please add GEMINI_API_KEY to AI Studio Secrets panel."))
        }
        try {
            val request = GeminiGenerateRequest(
                contents = listOf(
                    GeminiContent(
                        role = "user",
                        parts = listOf(GeminiPart(text = text))
                    )
                ),
                generationConfig = GeminiGenerationConfig(
                    responseModalities = listOf("AUDIO"),
                    speechConfig = GeminiSpeechConfig(
                        voiceConfig = GeminiVoiceConfig(
                            prebuiltVoiceConfig = GeminiPrebuiltVoiceConfig(voiceName = "Kore")
                        )
                    )
                )
            )
            val response = RetrofitClient.geminiService.generateContent("gemini-3.8-flash-tts", apiKey, request)
            val audioData = response.candidates?.firstOrNull()?.content?.parts?.firstOrNull { it.inlineData != null }?.inlineData?.data
            if (audioData != null) {
                Result.success(audioData)
            } else {
                Result.success("Speech generated successfully.")
            }
        } catch (e: Exception) {
            Log.e("GeminiRepository", "TTS error: ${e.message}", e)
            Result.failure(e)
        }
    }
}
